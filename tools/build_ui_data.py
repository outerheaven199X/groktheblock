"""Embed the synthetic example reports into ui/data/reports.js so the v6 UI makes no fetch/XHR.
Usage: python tools/build_ui_data.py [--check]   (--check exits 1 if ui/data/reports.js is stale)"""
import json, sys
from pathlib import Path
R = Path(__file__).resolve().parents[1]
OUT = R / "ui/data/reports.js"

def render():
    reps = []
    for f in sorted((R / "examples").glob("*.json")):
        j = json.loads(f.read_text())
        reps.append({"name": f.name, "json": j})
    body = json.dumps(reps, ensure_ascii=False, separators=(",", ":"))
    return ("// GENERATED by tools/build_ui_data.py from examples/*.json (synthetic only). Do not edit.\n"
            "window.GTB_REPORTS=" + body + ";\n")

if __name__ == "__main__":
    s = render()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text() == s
        print("ui/data/reports.js", "up to date" if ok else "STALE"); sys.exit(0 if ok else 1)
    OUT.parent.mkdir(parents=True, exist_ok=True); OUT.write_text(s); print("wrote", OUT, len(s))
